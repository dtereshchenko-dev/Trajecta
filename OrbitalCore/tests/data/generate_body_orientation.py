"""Generate immutable IAU coefficients and independent CSPICE reference matrices.

Usage: python generate_body_orientation.py <NAIF-kernel-directory>
Requires spiceypy only for regeneration, not for the application or C++ tests.
Kernels: https://naif.jpl.nasa.gov/pub/naif/generic_kernels/
  pck/pck00011.tpc
  pck/moon_pa_de440_200625.bpc
  fk/satellites/moon_de440_250416.tf
"""
import hashlib
import json
from pathlib import Path
import sys

import spiceypy as spice

reference = Path(sys.argv[1])
core = Path(__file__).resolve().parents[2]
files = ["pck00011.tpc", "moon_de440_250416.tf", "moon_pa_de440_200625.bpc"]
hashes = {name: hashlib.sha256((reference / name).read_bytes()).hexdigest() for name in files}
for name in files:
    spice.furnsh(str(reference / name))


def values(name):
    try:
        return spice.gdpool(name, 0, 200).tolist()
    except (spice.utils.exceptions.SpiceKERNELVARNOTFOUND,
            spice.utils.exceptions.NotFoundError):
        return []


def numbers(items):
    return ", ".join(format(float(value), ".17g") for value in items)


names = [(199, "Mercury"), (299, "Venus"), (499, "Mars"), (599, "Jupiter"),
         (699, "Saturn"), (799, "Uranus"), (899, "Neptune")]
lines = [
    "#pragma once", "", "// Generated by tests/data/generate_body_orientation.py.",
    "// NAIF pck00011.tpc; polynomial angles in degrees, T in Julian centuries.",
    "// SHA256: " + hashes["pck00011.tpc"],
    '#include "orbital_core/hazard/Planet.h"', "#include <array>", "#include <span>", "",
    "namespace orbital_core::hazard::orientation {",
    "using Polynomial = std::array<double, 3>;",
    "struct PeriodicTerm { Polynomial phase; double ra; double dec; double pm; };",
    "struct Model {",
    "    Planet planet;",
    "    Polynomial ra, dec, pm;",
    "    std::span<const PeriodicTerm> periodic;",
    "    const char* frame;",
    "};", "",
]
models = []
for body, name in names:
    base = f"BODY{body}_"
    periodic = [values(base + "NUT_PREC_" + key) for key in ["RA", "DEC", "PM"]]
    count = max(map(len, periodic), default=0)
    phase_degree = values(f"BODY{body // 100}_MAX_PHASE_DEGREE") or [1]
    degree = int(phase_degree[0])
    assert degree <= 2
    phases = values(f"BODY{body // 100}_NUT_PREC_ANGLES")
    assert len(phases) >= count * (degree + 1)
    terms = []
    for i in range(count):
        amplitudes = [v[i] if i < len(v) else 0 for v in periodic]
        if any(amplitudes):
            phase = phases[i * (degree + 1):(i + 1) * (degree + 1)] + [0] * (2 - degree)
            terms.append("    {{" + numbers(phase) + "}, " + numbers(amplitudes) + "},")
    if terms:
        lines += [f"inline constexpr PeriodicTerm k{name}Terms[] = {{", *terms, "};", ""]
    polynomials = [values(base + key) for key in ["POLE_RA", "POLE_DEC", "PM"]]
    assert all(len(v) == 3 for v in polynomials)
    models.append("    {Planet::" + name + ", " +
                  ", ".join("{" + numbers(v) + "}" for v in polynomials) +
                  (f", k{name}Terms" if terms else ", {}") + f', "IAU_{name.upper()}"' + "},")
lines += ["inline constexpr Model kModels[] = {", *models, "};", ""]
pa_to_me = spice.pxform("MOON_PA_DE440", "MOON_ME_DE440_ME421", 0)
lines += [
    "// Constant PA -> ME421-aligned transformation from moon_de440_250416.tf.",
    "// SHA256: " + hashes["moon_de440_250416.tf"],
    "inline constexpr double kMoonPaToMe[3][3] = {",
    *["    {" + numbers(row) + "}," for row in pa_to_me],
    "};", "}", "",
]
(core / "src/hazard/IauRotationData.h").write_text("\n".join(lines), encoding="ascii")

samples = []
for mjd in [15020.5, 51544.5, 55197.125, 60000.25, 63688.0, 69807.5, 88069.5]:
    et = (mjd - 51544.5) * 86400
    for _, name in names:
        frame = f"IAU_{name.upper()}"
        samples.append(dict(body=name, mjd_tdb=mjd, frame=frame,
                            matrix=spice.pxform("J2000", frame, et).tolist()))
    samples.append(dict(body="Moon", mjd_tdb=mjd, frame="MOON_ME_DE440_ME421",
                        matrix=spice.pxform("J2000", "MOON_ME_DE440_ME421", et).tolist()))
(core / "tests/data/body_orientation_expected.json").write_text(
    json.dumps(dict(toolkit=spice.tkvrsn("TOOLKIT"), sources=hashes, samples=samples), indent=2) + "\n")
print(f"Generated {len(names)} planetary models and {len(samples)} CSPICE reference matrices.")
